package termfont

import "fmt"

// The glyph tables. Segment-display flavored ASCII art: horizontal bars
// are "_" (lit at the bottom of their row), verticals are "|", diagonals
// are "/" and "\". Height 2 has no room for a bar row, so it leans on
// "~" overlines and brackets to stay legible. Every glyph is height rows
// of equal-width printable ASCII; rows carry their own trailing padding.
//
// Lowercase input folds onto these uppercase shapes. Height 1 never
// consults a table — it is the terminal's own font.

// glyphSets maps an art height (2-5) to its rune glyph table.
var glyphSets = map[int]map[rune][]string{
	2: glyphs2,
	3: glyphs3,
	4: glyphs4,
	5: glyphs5,
}

// validateGlyphSet checks a table: every glyph has exactly height rows,
// the rows are rectangular and non-empty, and the art is printable ASCII.
func validateGlyphSet(height int, set map[rune][]string) error {
	if len(set) == 0 {
		return fmt.Errorf("height %d: empty glyph table", height)
	}
	for r, rows := range set {
		if len(rows) != height {
			return fmt.Errorf("height %d: glyph %q has %d rows", height, r, len(rows))
		}
		w := len(rows[0])
		if w == 0 {
			return fmt.Errorf("height %d: glyph %q is zero-width", height, r)
		}
		for i, row := range rows {
			if len(row) != w {
				return fmt.Errorf("height %d: glyph %q row %d is %d bytes, want %d", height, r, i, len(row), w)
			}
			for j := 0; j < len(row); j++ {
				if row[j] < ' ' || row[j] > '~' {
					return fmt.Errorf("height %d: glyph %q row %d byte %d (0x%02x) is not printable ASCII", height, r, i, j, row[j])
				}
			}
		}
	}
	return nil
}

